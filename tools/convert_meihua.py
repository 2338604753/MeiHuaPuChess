def convert():
    all_records = []
    for rid, game in games.items():
        moves_out = []
        for i, (side, notation, fr, fc, tr, tc, hints) in enumerate(game["moves"]):
            # 镜像：newCol = 8 - oldCol
            nfc = 8 - fc
            ntc = 8 - tc
            moves_out.append({
                "step": i + 1,
                "side": side,
                "notation": notation,
                "fromRow": fr,
                "fromCol": nfc,
                "toRow": tr,
                "toCol": ntc,
                "hints": hints
            })
        all_records.append({
            "id": rid,
            "title": game["title"],
            "category": "卷上·屏风马破当头炮",
            "description": game["desc"],
            "moves": moves_out
        })
    return {"records": all_records}

